function loadUser() {
  try {
    const saved = localStorage.getItem("quentro-user");
    if (saved) {
      const user = JSON.parse(saved);
      user.proofs = user.proofs || [];
      return user;
    }
  } catch (e) {}
  return null;
}

function loadEvents() {
  try {
    const saved = localStorage.getItem("quentro-events");
    if (saved) return JSON.parse(saved);
  } catch (e) {}
  return structuredClone(SEED);
}

function save() {
  localStorage.setItem("quentro-events", JSON.stringify(state.events));
}

function t() {
  return COPY[state.lang];
}

function go(view, extra) {
  state.profileMsg = "";
  state.menuOpen = false;
  Object.assign(state, extra || {}, { notice: "" });
  if (GUARDED.includes(view) && !state.user) {
    state.afterLogin = view;
    view = "login";
  }
  state.view = view;
  if (view === "home") location.hash = "";
  else location.hash = view + (state.eventId && !["login", "dashboard", "create", "app", "alerts", "profile"].includes(view) ? "/" + state.eventId : "");
  render();
}

