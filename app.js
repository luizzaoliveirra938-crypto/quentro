function qrSvg(seed) {
  const n = 25;
  let cells = "";
  function bit(x, y) {
    const v = Math.imul(x + 3, 374761393) ^ Math.imul(y + 7, 668265263) ^ seed;
    return (v >>> 0) % 3 !== 0;
  }
  function finder(ox, oy) {
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 7; x++) {
        const edge = x === 0 || y === 0 || x === 6 || y === 6 || (x >= 2 && x <= 4 && y >= 2 && y <= 4);
        if (edge) cells += `<rect x="${ox + x}" y="${oy + y}" width="1" height="1"/>`;
      }
    }
  }
  finder(0, 0);
  finder(n - 7, 0);
  finder(0, n - 7);
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      const inFinder = (x < 8 && y < 8) || (x > n - 9 && y < 8) || (x < 8 && y > n - 9);
      if (!inFinder && bit(x, y)) cells += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
    }
  }
  return `<svg viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges">${cells}</svg>`;
}

