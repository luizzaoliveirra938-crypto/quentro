document.body.addEventListener("submit", (e) => {
  if (e.target.id === "event-form") {
    e.preventDefault();
    const data = Object.fromEntries(new FormData(e.target));
    const name = String(data.name || "").trim();
    const venue = String(data.venue || "").trim();
    if (!name || !venue || !data.date) {
      state.loginError = t().needEvent;
      return render();
    }
    const when = new Date(data.date + "T12:00:00");
    const weekdays = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
    const months = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
    const qty = Math.min(20, Math.max(1, Number(data.qty) || 1));
    const startSeat = String(data.seat || "1").trim();
    const base = Number(startSeat);
    const seats = Array.from({ length: qty }, (_, i) => ({
      section: String(data.section || "A").trim() || "A",
      row: String(data.row || "H").trim() || "H",
      seat: Number.isFinite(base) ? String(base + i) : (i === 0 ? startSeat : startSeat + "-" + (i + 1)),
    }));
    const clock = (value, fallback) => {
      const v = String(value || fallback);
      return v.length === 5 ? v + " hs" : v;
    };
    const image = String(data.image || "").trim();
    let imageUrl = "";
    if (image) {
      try {
        const parsed = new URL(image);
        if (parsed.protocol !== "http:" && parsed.protocol !== "https:") throw new Error("bad");
        imageUrl = parsed.href;
      } catch (err) {
        state.loginError = t().badImage;
        return render();
      }
    }
    state.events.unshift({
      id: "ev-" + Date.now(),
      name,
      venue,
      month: months[when.getMonth()] + " " + when.getFullYear(),
      when: weekdays[when.getDay()] + " " + when.getDate(),
      poster: "fest",
      posterText: name.slice(0, 2).toUpperCase(),
      image: imageUrl,
      status: "upcoming",
      door: clock(data.door, "17:00"),
      starts: clock(data.starts, "20:00"),
      sector: String(data.sector || "Stalls").trim(),
      access: String(data.access || "Gate B").trim(),
      rate: "General - $" + String(data.price || "0").replace(/^\$/, ""),
      seats,
    });
    state.loginError = "";
    state.tab = "upcoming";
    save();
    return go("app");
  }
  if (e.target.id === "profile-form") {
    e.preventDefault();
    const data = Object.fromEntries(new FormData(e.target));
    const name = String(data.name || "").trim();
    const email = String(data.email || "").trim().toLowerCase();
    if (!name || !email.includes("@")) {
      state.profileMsg = t().needProfile;
      return render();
    }
    state.user.name = name;
    state.user.email = email;
    state.profileMsg = t().profileSaved;
    localStorage.setItem("quentro-user", JSON.stringify(state.user));
    return render();
  }
  if (e.target.id === "proof-form") {
    e.preventDefault();
    const data = Object.fromEntries(new FormData(e.target));
    const ref = String(data.ref || "").trim();
    const amount = String(data.amount || "").trim();
    if (!ref || !amount) {
      state.profileMsg = t().needProof;
      return render();
    }
    let imageUrl = "";
    const image = String(data.image || "").trim();
    if (image) {
      try {
        const parsed = new URL(image);
        if (parsed.protocol !== "http:" && parsed.protocol !== "https:") throw new Error("bad");
        imageUrl = parsed.href;
      } catch (err) {
        state.profileMsg = t().badImage;
        return render();
      }
    }
    state.user.proofs = state.user.proofs || [];
    state.user.proofs.unshift({
      ref,
      amount: amount.startsWith("$") ? amount : "$" + amount,
      date: data.date || "",
      image: imageUrl,
    });
    state.profileMsg = t().proofSaved;
    localStorage.setItem("quentro-user", JSON.stringify(state.user));
    return render();
  }
  if (e.target.id !== "login-form") return;
  e.preventDefault();
  const email = document.getElementById("login-email").value.trim().toLowerCase();
  const password = document.getElementById("login-password").value;
  if (email !== DEMO.email || password !== DEMO.password) {
    state.loginError = t().badLogin;
    return render();
  }
  state.user = { email: DEMO.email, name: DEMO.name, proofs: [] };
  state.loginError = "";
  localStorage.setItem("quentro-user", JSON.stringify(state.user));
  go(state.afterLogin || "dashboard");
});

document.body.addEventListener("click", (e) => {
  if (e.target.closest("#account-btn")) {
    state.menuOpen = !state.menuOpen;
    return render();
  }
  if (state.menuOpen && !e.target.closest(".account-menu")) {
    state.menuOpen = false;
    render();
  }
  if (e.target.closest("#logout")) {
    state.user = null;
    localStorage.removeItem("quentro-user");
    return go("home");
  }
  if (e.target.closest(".preview")) return go("dashboard");
  const el = e.target.closest("[data-go],[data-lang],[data-tab],[data-event],[data-seat],[data-pick],[data-faq],[data-open-ticket],#send");
  if (!el) return;
  if (el.dataset.go) {
    const view = el.dataset.go;
    if (view === "pass" && !state.eventId) return go("app");
    return go(view);
  }
  if (el.dataset.lang) {
    state.lang = el.dataset.lang;
    return render();
  }
  if (el.dataset.tab) {
    state.tab = el.dataset.tab;
    return render();
  }
  if (el.dataset.event) {
    state.eventId = el.dataset.event;
    state.ticketIndex = 0;
    state.selected = {};
    return go("pass");
  }
  if (el.dataset.openTicket) {
    state.eventId = el.dataset.openTicket;
    state.ticketIndex = 0;
    return go("pass");
  }
  if (el.dataset.seat) {
    state.ticketIndex = Number(el.dataset.seat);
    return render();
  }
  if (el.dataset.pick != null) {
    const i = el.dataset.pick;
    state.selected[i] = !state.selected[i];
    return render();
  }
  if (el.dataset.faq != null) {
    const i = Number(el.dataset.faq);
    state.openFaq = state.openFaq === i ? -1 : i;
    return render();
  }
  if (el.id === "send") {
    const input = document.getElementById("email");
    state.email = input ? input.value.trim() : "";
    const indexes = Object.keys(state.selected).filter((k) => state.selected[k]).map(Number);
    if (!state.email.includes("@") || !indexes.length) {
      state.notice = state.email.includes("@") ? "Select at least one ticket." : "Enter a valid email.";
      return render();
    }
    const ev = state.events.find((e) => e.id === state.eventId);
    ev.seats = ev.seats.filter((_, i) => !indexes.includes(i));
    state.selected = {};
    state.notice = t().sent;
    save();
    render();
  }
});

